import {chmodSync, existsSync, readFileSync, writeFileSync} from 'node:fs';
import type {PlatformType} from '../core/system';

export interface MavenWrapperInput {
    jdkHome: string;
    toolHome: string;
    toolBin: string;
    userSettingsPath: string;
    localRepoPath: string;
    platform: PlatformType;
    scriptPath: string;
}

export interface MavenWrapperResult {
    updated: boolean;
    scriptPath: string;
}

function escapeBatch(value: string): string {
    return value.replace(/%/g, '%%');
}

function escapeBashDouble(value: string): string {
    return value.replace(/(["`\\$])/g, '\\$1');
}

function buildWindowsScript(input: MavenWrapperInput): string {
    const mvnCmd = `${input.toolBin}\\mvn.cmd`;
    const javaHome = escapeBatch(input.jdkHome);
    const mavenHome = escapeBatch(input.toolHome);
    const settingsXml = escapeBatch(input.userSettingsPath);
    const repoLocal = escapeBatch(input.localRepoPath);
    const mvnCmdEscaped = escapeBatch(mvnCmd);
    return [
        '@echo off',
        'REM Auto-generated by Jaenvtix. Do not edit manually.',
        'setlocal',
        `set "JAVA_HOME=${javaHome}"`,
        `set "MAVEN_HOME=${mavenHome}"`,
        'set "M2_HOME=%MAVEN_HOME%"',
        'set "PATH=%JAVA_HOME%\\bin;%MAVEN_HOME%\\bin;%PATH%"',
        `call "${mvnCmdEscaped}" -s "${settingsXml}" -Dmaven.repo.local="${repoLocal}" %*`,
        'exit /b %ERRORLEVEL%',
        '',
    ].join('\r\n');
}

function buildUnixScript(input: MavenWrapperInput): string {
    const mvnBin = `${input.toolBin}/mvn`;
    return [
        '#!/usr/bin/env sh',
        '# Auto-generated by Jaenvtix. Do not edit manually.',
        `export JAVA_HOME="${escapeBashDouble(input.jdkHome)}"`,
        `export MAVEN_HOME="${escapeBashDouble(input.toolHome)}"`,
        'export M2_HOME="$MAVEN_HOME"',
        'export PATH="$JAVA_HOME/bin:$MAVEN_HOME/bin:$PATH"',
        `exec "${escapeBashDouble(mvnBin)}" -s "${escapeBashDouble(input.userSettingsPath)}" -Dmaven.repo.local="${escapeBashDouble(input.localRepoPath)}" "$@"`,
        '',
    ].join('\n');
}

export function writeJaenvtixMavenWrapper(input: MavenWrapperInput): MavenWrapperResult {
    const content = input.platform === 'windows' ? buildWindowsScript(input) : buildUnixScript(input);
    const existing = existsSync(input.scriptPath) ? readFileSync(input.scriptPath, 'utf-8') : null;
    const updated = existing !== content;

    if (updated) {
        writeFileSync(input.scriptPath, content, 'utf-8');
    }

    if (input.platform !== 'windows') {
        chmodSync(input.scriptPath, 0o755);
    }

    return { updated, scriptPath: input.scriptPath };
}
