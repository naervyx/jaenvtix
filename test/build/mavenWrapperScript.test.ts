import {describe, it, afterEach} from 'node:test';
import assert from 'node:assert/strict';
import {promises as fs, statSync} from 'node:fs';
import {join} from 'node:path';

import {writeJaenvtixMavenWrapper, type MavenWrapperInput} from '../../src/build/mavenWrapperScript';
import {createTempDir, removeTempDir} from '../fixtures/tempDir';

const isWindows = process.platform === 'win32';

interface ScenarioInput {
    platform: MavenWrapperInput['platform'];
    scriptName: string;
    overrides?: Partial<MavenWrapperInput>;
}

async function buildScenario({platform, scriptName, overrides}: ScenarioInput): Promise<{
    input: MavenWrapperInput;
    cleanup: () => Promise<void>;
}> {
    const tempRoot = await createTempDir();
    const input: MavenWrapperInput = {
        jdkHome: 'C:\\jdks\\21',
        toolHome: 'C:\\maven\\3.9.6',
        toolBin: 'C:\\maven\\3.9.6\\bin',
        userSettingsPath: 'C:\\Users\\dev\\.m2\\settings.xml',
        localRepoPath: 'C:\\Users\\dev\\.m2\\repository',
        platform,
        scriptPath: join(tempRoot, scriptName),
        ...overrides,
    };
    return {input, cleanup: () => removeTempDir(tempRoot)};
}

describe('writeJaenvtixMavenWrapper — Windows batch script', () => {
    const cleanups: (() => Promise<void>)[] = [];

    afterEach(async () => {
        await Promise.all(cleanups.splice(0).map((fn) => fn()));
    });

    it('emits CRLF-delimited batch with @echo off, setlocal, and the auto-generated marker', async () => {
        const {input, cleanup} = await buildScenario({platform: 'windows', scriptName: 'jaenvtix-mvn.cmd'});
        cleanups.push(cleanup);

        const result = writeJaenvtixMavenWrapper(input);

        const written = await fs.readFile(input.scriptPath, 'utf-8');
        assert.equal(result.updated, true);
        assert.match(written, /^@echo off\r\n/);
        assert.match(written, /REM Auto-generated by Jaenvtix\. Do not edit manually\./);
        assert.match(written, /setlocal/);
        assert.match(written, /set "JAVA_HOME=C:\\jdks\\21"/);
        assert.match(written, /set "MAVEN_HOME=C:\\maven\\3\.9\.6"/);
        assert.match(written, /set "PATH=%JAVA_HOME%\\bin;%MAVEN_HOME%\\bin;%PATH%"/);
        assert.match(written, /call "C:\\maven\\3\.9\.6\\bin\\mvn\.cmd" -s "C:\\Users\\dev\\.m2\\settings\.xml" -Dmaven\.repo\.local="C:\\Users\\dev\\.m2\\repository" %\*/);
        assert.match(written, /exit \/b %ERRORLEVEL%/);
    });

    it('escapes literal % in paths so batch never expands them', async () => {
        const {input, cleanup} = await buildScenario({
            platform: 'windows',
            scriptName: 'jaenvtix-mvn.cmd',
            overrides: {jdkHome: 'C:\\jdks\\1%23'},
        });
        cleanups.push(cleanup);

        writeJaenvtixMavenWrapper(input);
        const written = await fs.readFile(input.scriptPath, 'utf-8');
        assert.match(written, /set "JAVA_HOME=C:\\jdks\\1%%23"/);
    });

    it('reports updated=false when the script content is already current', async () => {
        const {input, cleanup} = await buildScenario({platform: 'windows', scriptName: 'jaenvtix-mvn.cmd'});
        cleanups.push(cleanup);

        writeJaenvtixMavenWrapper(input);
        const second = writeJaenvtixMavenWrapper(input);
        assert.equal(second.updated, false);
    });
});

describe('writeJaenvtixMavenWrapper — Unix shell script', () => {
    const cleanups: (() => Promise<void>)[] = [];

    afterEach(async () => {
        await Promise.all(cleanups.splice(0).map((fn) => fn()));
    });

    it('emits LF-delimited shell script with shebang, exports, and exec mvn', async () => {
        const {input, cleanup} = await buildScenario({
            platform: 'linux',
            scriptName: 'jaenvtix-mvn',
            overrides: {
                jdkHome: '/home/dev/.jaenvtix/jdk-17',
                toolHome: '/home/dev/.jaenvtix/jdk-17/mvn-custom',
                toolBin: '/home/dev/.jaenvtix/jdk-17/mvn-custom/bin',
                userSettingsPath: '/home/dev/.m2/settings.xml',
                localRepoPath: '/home/dev/.m2/repository',
            },
        });
        cleanups.push(cleanup);

        writeJaenvtixMavenWrapper(input);
        const written = await fs.readFile(input.scriptPath, 'utf-8');

        assert.equal(written.startsWith('#!/usr/bin/env sh\n'), true);
        assert.equal(written.includes('\r\n'), false);
        assert.match(written, /# Auto-generated by Jaenvtix\. Do not edit manually\./);
        assert.match(written, /export JAVA_HOME="\/home\/dev\/\.jaenvtix\/jdk-17"/);
        assert.match(written, /export MAVEN_HOME="\/home\/dev\/\.jaenvtix\/jdk-17\/mvn-custom"/);
        assert.match(written, /export M2_HOME="\$MAVEN_HOME"/);
        assert.match(written, /export PATH="\$JAVA_HOME\/bin:\$MAVEN_HOME\/bin:\$PATH"/);
        assert.match(written, /exec "\/home\/dev\/\.jaenvtix\/jdk-17\/mvn-custom\/bin\/mvn" -s "\/home\/dev\/\.m2\/settings\.xml" -Dmaven\.repo\.local="\/home\/dev\/\.m2\/repository" "\$@"/);
    });

    it('escapes shell-active characters ($ ` " \\) in path values', async () => {
        const {input, cleanup} = await buildScenario({
            platform: 'darwin',
            scriptName: 'jaenvtix-mvn',
            overrides: {
                jdkHome: '/Users/dev/jdk$1`with"quote\\and-backslash',
            },
        });
        cleanups.push(cleanup);

        writeJaenvtixMavenWrapper(input);
        const written = await fs.readFile(input.scriptPath, 'utf-8');
        assert.match(written, /export JAVA_HOME="\/Users\/dev\/jdk\\\$1\\`with\\"quote\\\\and-backslash"/);
    });

    it('chmods the script to 0o755 on POSIX', {skip: isWindows}, async () => {
        const {input, cleanup} = await buildScenario({platform: 'linux', scriptName: 'jaenvtix-mvn'});
        cleanups.push(cleanup);

        writeJaenvtixMavenWrapper(input);
        const stat = statSync(input.scriptPath);
        assert.equal(stat.mode & 0o777, 0o755);
    });
});
